"""Write the SBML Test Suite sample suite (docs/plan-sbml-test-suite.md, S5 and S9).

    uv run python scripts/sbml_sample_suite.py --release 3.5.0

Reads the release's semantic archive (fetched once and cached, like a suite run's), and picks the time-course cases
that cover every tag and every pair of tags found together (`sbml_test_suite.pick_sample`). Re-running it at the same
release writes the same file. A picked case whose SED-ML cannot be written stays in (S6, S12): its suite row records
why. Regenerate rather than edit the sources.
"""

import argparse
import asyncio
from pathlib import Path

from compose_api.sedml import sbml_test_suite as sts

HEADER = """# The SBML Test Suite sample (docs/plan-sbml-test-suite.md, S5 and S9): {count} of release {release}'s
# {total} time-course cases, chosen so every tag and every pair of tags that some case has together is in one of
# them.
# Generated by scripts/sbml_sample_suite.py; regenerate rather than edit the sources. Each case is judged by its
# expected results, with its own tolerances (S3, S4); the solvers' agreement with each other is shown, not decisive.
# {unwritable} of these cases cannot be written as SED-ML yet; their rows say why (findings 9 and 10, S12).
# Each source's comment lists its tags.
name: {name}
description: "{count} SBML Test Suite {release} cases covering every tag and every pair of tags, each run on COPASI,
  Tellurium and VCell and judged by the suite's expected results."
solvers: [copasi, tellurium, vcell]
judged_by: reference
sources:
"""


async def main(release: str, name: str) -> None:
    archive = await sts.release_archive(release)
    found: dict[str, frozenset[str]] = {}
    writable: dict[str, bool] = {}
    for number in sts.case_numbers(archive):
        try:
            case = sts.read_case(archive, release, number)
        except sts.CaseNotSupportedError:  # not a time course
            continue
        found[number] = sts.tags(case)
        try:
            sts.sedml_document(case)
            writable[number] = True
        except ValueError:
            writable[number] = False
    chosen = sts.pick_sample(found, writable)
    lines = [
        f"  - {sts.KIND}:{release}/{c}  # {', '.join(sorted(found[c]))}{'' if writable[c] else ' (not writable)'}"
        for c in chosen
    ]
    path = Path("examples") / name / "suite.yaml"
    path.parent.mkdir(parents=True, exist_ok=True)
    header = HEADER.format(
        count=len(chosen), release=release, total=len(found), name=name,
        unwritable=sum(1 for c in chosen if not writable[c]),
    )  # fmt: skip
    path.write_text(header + "\n".join(lines) + "\n")
    print(f"{path}: {len(chosen)} cases of {len(found)}, covering {len(set().union(*found.values()))} tags")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--release", default="3.5.0", choices=sorted(sts.RELEASES))
    parser.add_argument("--name", default="sbml-test-suite-sample")
    args = parser.parse_args()
    asyncio.run(main(args.release, args.name))
