"""An environment's interface manifest is its version's read-back (docs/plan-environment-composition.md, D8.4).

Every version's image is read back when it is built or registered (``environments/contents.py``): what it installed
and, in the shared ``pbg-interfaces/1`` form, every class it provides. The manifest an environment is checked and
translated against is its default version's, or a named version's, served as it was read; nothing is committed or
regenerated by CI. Each component is annotated with its registry entry, as the committed files' were.
"""

import json
from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import TYPE_CHECKING, Any

from compose_api.registry.environments import EntryRef, InterfaceManifest
from compose_api.registry.manifest import Manifest, load_manifest

if TYPE_CHECKING:
    from compose_api.db.database_service import DatabaseService


def annotated(interfaces: Mapping[str, Any], registry: Manifest | None = None) -> InterfaceManifest:
    """A read-back manifest with each component's registry entry (by its module's root)."""
    manifest = InterfaceManifest.model_validate(dict(interfaces))
    registry = registry or load_manifest()
    for component in manifest.components:
        entry = registry.entry_for_module(component.module or component.address.split("!", 1)[-1])
        component.registry_entry = None if entry is None else EntryRef(id=entry.id, level=entry.level)
    return manifest


async def interfaces_of(
    database_service: "DatabaseService | None", environment: str, number: int | None = None
) -> dict[str, Any] | None:
    """What a version of ``environment`` provides, as read back (``number``, or its default); None when there is no
    such version or nothing has been read back from it yet."""
    if database_service is None:
        return None
    environments_db = database_service.get_environments_db()
    version = (
        await environments_db.get_by_number(environment, number)
        if number is not None
        else await environments_db.get_default_detail(environment)
    )
    interfaces = version.interfaces if version is not None else None
    return interfaces if interfaces and interfaces.get("components") is not None else None


async def manifest_of(
    database_service: "DatabaseService | None", environment: str, registry: Manifest | None = None
) -> InterfaceManifest | None:
    """The environment's manifest: its default version's read-back, annotated."""
    interfaces = await interfaces_of(database_service, environment)
    return annotated(interfaces, registry) if interfaces is not None else None


async def manifests_of(
    database_service: "DatabaseService | None", environments: Iterable[str]
) -> dict[str, InterfaceManifest | None]:
    """Each environment's manifest (None where it has none yet)."""
    registry = load_manifest()
    return {name: await manifest_of(database_service, name, registry) for name in environments}


async def manifest_files(
    database_service: "DatabaseService | None", environments: Mapping[str, int | None], directory: Path
) -> list[Path]:
    """Each environment's manifest at its version (None: its default) written as ``<name>.json`` into ``directory``,
    for process-bigraph-lang, which reads manifests from files. An environment with none is left out."""
    files = []
    for name, number in sorted(environments.items()):
        interfaces = await interfaces_of(database_service, name, number)
        if interfaces is not None:
            path = directory / f"{name}.json"
            path.write_text(json.dumps(interfaces))
            files.append(path)
    return files
