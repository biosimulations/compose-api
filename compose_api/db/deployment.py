"""The deployment's stable identity (#543), reported as `deployment_id` on `GET /health`.

It lives in the deployment's own database, so it survives restarts, upgrades, more replicas and a new hostname, and
two deployments (production, a dev stack, a laptop) never share one unless they share a database. It is generated by
whichever process first finds the row missing; concurrent replicas race on the singleton key and all read the winner.
Clients compare it for equality only; nothing parses it.
"""

import uuid

from sqlalchemy import select
from sqlalchemy.dialects.postgresql import insert
from sqlalchemy.ext.asyncio import AsyncEngine

from compose_api.db.tables.deployment_tables import SINGLETON_ID, ORMDeployment


async def ensure_deployment_id(engine: AsyncEngine) -> str:
    """Return this database's deployment id, creating it the first time."""
    async with engine.begin() as conn:
        await conn.execute(
            insert(ORMDeployment)
            .values(id=SINGLETON_ID, deployment_id=str(uuid.uuid4()))
            .on_conflict_do_nothing(index_elements=[ORMDeployment.id])
        )
        result = await conn.execute(select(ORMDeployment.deployment_id).where(ORMDeployment.id == SINGLETON_ID))
        return result.scalar_one()
